"""PDF report generation."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

from utils.helpers import to_json


def generate_pdf_report(
    target: str,
    scan: dict[str, Any],
    risk: dict[str, Any],
    mitre: list[dict[str, Any]],
    ai_report: str,
    output_path: Path | None = None,
) -> Path:
    """Generate a professional PDF report and return its path."""

    output = output_path or Path("history") / f"{target.replace('.', '_')}_report.pdf"
    output.parent.mkdir(parents=True, exist_ok=True)
    styles = getSampleStyleSheet()
    doc = SimpleDocTemplate(str(output), pagesize=A4)
    story: list[Any] = []

    sections = [
        ("Executive Summary", risk.get("risk_summary", "")),
        ("Target Information", to_json({"target": target, "ip": scan.get("ip")}, pretty=True)),
        ("Attack Surface", to_json({"ports": scan.get("ports"), "services": scan.get("services")}, pretty=True)),
        ("Open Ports", to_json(scan.get("ports", []), pretty=True)),
        ("Technologies", to_json(scan.get("technologies", []), pretty=True)),
        ("Headers", to_json(scan.get("headers", {}), pretty=True)),
        ("SSL", to_json(scan.get("ssl", {}), pretty=True)),
        ("MITRE", to_json(mitre, pretty=True)),
        ("Recommendations", risk.get("risk_summary", "")),
        ("AI Analysis", ai_report.replace("\n", "<br/>")),
        ("Footer", f"Generated by AI-SOC Assistant at {datetime.now().isoformat()}"),
    ]

    story.append(Paragraph("AI-SOC Assistant Security Report", styles["Title"]))
    story.append(Spacer(1, 12))
    for title, content in sections:
        story.append(Paragraph(title, styles["Heading2"]))
        story.append(Paragraph(str(content).replace("\n", "<br/>"), styles["BodyText"]))
        story.append(Spacer(1, 10))
    doc.build(story)
    return output

